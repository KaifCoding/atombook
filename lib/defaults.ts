const numbering = (): Record<DocType, NumberingConfig> => {
  const out = {} as Record<DocType, NumberingConfig>;
  (Object.keys(DOC_TYPES) as DocType[]).forEach((t) => {
    out[t] = { prefix: DOC_TYPES[t].defaultPrefix, padding: 4, start: 1 };
  });
  return out;
};

